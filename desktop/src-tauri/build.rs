fn main() {
    println!("cargo:rerun-if-env-changed=PULSE_TEST_MANIFEST");
    tauri_build::try_build(tauri_build::Attributes::new().app_manifest(
        tauri_build::AppManifest::new().commands(&[
            "pulse_update_info",
            "pulse_update_check",
            "pulse_update_download",
            "pulse_update_cancel",
            "pulse_update_preferences",
            "pulse_update_install",
        ]),
    ))
    .expect("Could not build Pulse desktop permissions");

    // Tauri's resource manifest is attached to the app, not Cargo's lib-test
    // executable. The test harness also needs Common Controls v6 on Windows.
    // Enable linker embedding only for `cargo test --lib`; normal packaging
    // keeps the manifest generated by tauri-build.
    if std::env::var("PULSE_TEST_MANIFEST").as_deref() == Ok("1")
        && std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("windows")
        && std::env::var("CARGO_CFG_TARGET_ENV").as_deref() == Ok("msvc")
    {
        let manifest = std::path::PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").unwrap())
            .join("tests/windows-test.manifest");
        println!("cargo:rerun-if-changed={}", manifest.display());
        println!("cargo:rustc-link-arg=/MANIFEST:EMBED");
        println!("cargo:rustc-link-arg=/MANIFESTINPUT:{}", manifest.display());
    }
}
